impl Cmd {
    /// The command whose variant name is `id` (used by keybindings.json).
    pub fn from_id(id: &str) -> Option<Cmd> {
        COMMANDS.iter().map(|(_, _, c)| *c).find(|c| format!("{c:?}") == id)
    }
}

